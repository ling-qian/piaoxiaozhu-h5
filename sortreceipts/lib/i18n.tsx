// --- React Context ---

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextValue>({
  locale: "zh",
  setLocale: () => {},
  t: (key: string) => translations.zh[key] || key,
});

/**
 * 初始语言。
 *
 * 优先级：用户手动选过的 → 浏览器语言 → 英文。
 *
 * 默认英文而不是中文，因为 H5 首发面向海外。中文用户大概率装了中文浏览器，
 * 会走第二条分支；只有浏览器语言是第三种语言的人才落到英文兜底——
 * 那时英文也比中文更可能被看懂。
 */
function getInitialLocale(): Locale {
  if (typeof window !== "undefined") {
    const saved = localStorage.getItem("locale");
    if (saved === "zh" || saved === "en") return saved;

    const nav = navigator.language?.toLowerCase() ?? "";
    if (nav.startsWith("zh")) return "zh";
  }
  return "en";
}

/**
 * 服务端渲染用的确定性默认语言。
 *
 * 不能直接用 `getInitialLocale()` 做 `useState` 的初值：它读 localStorage 和
 * `navigator.language`，这两样在服务端都没有，于是服务端按默认值渲染、
 * 客户端按用户偏好渲染，两边文字对不上，React 报水合失败（#418）。
 *
 * 改成「首帧固定用默认值，挂载后再应用用户偏好」：代价是中文用户会看到
 * 极短一瞬的英文，换来的是没有水合错误——后者会让整棵子树重新渲染，
 * 更贵也更难排查。
 */
/**
 * 站点默认语言。与 lib/region.ts 的 REGION 保持一致，但这里不 import 它：
 * i18n 是叶子模块，反向依赖会让 region 的常量在两个模块间来回引用。
 * 海外版（不配或配成其它值）默认英文，国内版默认中文。
 */
const SSR_DEFAULT_LOCALE: Locale =
  process.env.NEXT_PUBLIC_REGION === "cn" ? "zh" : "en";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(SSR_DEFAULT_LOCALE);

  useEffect(() => {
    const preferred = getInitialLocale();
    if (preferred !== SSR_DEFAULT_LOCALE) setLocaleState(preferred);
  }, []);

  const setLocale = useCallback((loc: Locale) => {
    setLocaleState(loc);
    if (typeof window !== "undefined") {
      localStorage.setItem("locale", loc);
      // 同步写 cookie：服务端的 apiFetch 读不到 localStorage，只能读 cookie。
      // 不写的话，用户把界面切成中文、后端错误提示仍是英文——语言会分裂。
      document.cookie = `px_locale=${loc}; path=/; max-age=31536000; samesite=lax`;
    }
  }, []);

  const t = useCallback(
    (key: string) => translations[locale]?.[key] || translations.zh[key] || key,
    [locale]
  );

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}

// 非组件场景的纯函数（用于服务端等）
export function t(key: string, locale: Locale = "zh"): string {
  return translations[locale]?.[key] || translations.zh[key] || key;
}
